def seed_database(session: Session, force_refresh: bool = False) -> Dict[str, int]:
    """Ensure Zillow ZIP trends and verified Duval + St. Johns listings are populated."""
    zip_added = 0
    zip_updated = 0
    for zdata in get_jacksonville_zip_trends():
        existing_zip = session.exec(
            select(ZipTrend).where(ZipTrend.zip_code == zdata["zip_code"])
        ).first()
        if not existing_zip:
            session.add(ZipTrend(**zdata))
            zip_added += 1
        elif force_refresh or not existing_zip.county:
            for k, v in zdata.items():
                setattr(existing_zip, k, v)
            session.add(existing_zip)
            zip_updated += 1

    listings_added = 0
    listings_updated = 0

    for item in get_starter_jacksonville_listings():
        existing = session.exec(
            select(ForeclosureListing).where(
                ForeclosureListing.case_number == item["case_number"]
            )
        ).first()
        if not existing:
            listing = ForeclosureListing(**item)
            listing.recalculate_metrics_and_links()
            session.add(listing)
            listings_added += 1
        elif force_refresh or not existing.county or existing.address in OLD_SYNTHETIC_ADDRESSES:
            for k, v in item.items():
                setattr(existing, k, v)
            existing.updated_at = utc_now()
            existing.recalculate_metrics_and_links()
            session.add(existing)
            listings_updated += 1

    session.commit()
    return {
        "listings_added": listings_added,
        "listings_updated": listings_updated,
        "zip_trends_added": zip_added,
        "zip_trends_updated": zip_updated,
    }
